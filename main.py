from machine import ADC, Pin
import neopixel
import time


# ==========================================
# 1. MQ-2 설정
# ==========================================
# MQ-2의 AO(아날로그 출력) → A0 = GP26
mq2 = ADC(Pin(26))


# ==========================================
# 2. RGB LED Stick 설정
# ==========================================
# RGB LED Stick의 신호선 → D16 = GP16
# LED가 총 10개
NUM_LEDS = 10

led = neopixel.NeoPixel(
    Pin(16),
    NUM_LEDS
)


# ==========================================
# 3. 색상 설정
# ==========================================
OFF = (0, 0, 0)

GREEN = (0, 50, 0)       # 초록색
YELLOW = (50, 35, 0)     # 노란색
RED = (50, 0, 0)         # 빨간색


# ==========================================
# 4. LED 표시 함수
# ==========================================
def show_led(count):

    # 먼저 모든 LED 끄기
    for i in range(NUM_LEDS):
        led[i] = OFF

    # --------------------------------------
    # 1~5칸 : 초록색
    # --------------------------------------
    for i in range(min(count, 5)):
        led[i] = GREEN

    # --------------------------------------
    # 6~8칸 : 노란색
    # --------------------------------------
    if count > 5:
        for i in range(5, min(count, 8)):
            led[i] = YELLOW

    # --------------------------------------
    # 9~10칸 : 빨간색
    # --------------------------------------
    if count > 8:
        for i in range(8, min(count, 10)):
            led[i] = RED

    # 실제 LED에 적용
    led.write()


# ==========================================
# 5. 시작
# ==========================================
print("====================================")
print("       MQ-2 공기 상태 측정 시작")
print("====================================")

# 시작할 때 LED 모두 끄기
show_led(0)

print()
print("MQ-2 초기 측정을 시작합니다.")
print("약 2분 동안 측정한 후 기준값을 설정합니다.")
print()


# ==========================================
# 6. 2분 동안 초기 측정
# ==========================================
for sec in range(120):

    value = mq2.read_u16()

    print(
        "초기 측정값:",
        value,
        "| 남은 시간:",
        120 - sec,
        "초"
    )

    time.sleep(1)


# ==========================================
# 7. 2분 후 기준값 설정
#    20번 측정해서 평균 계산
# ==========================================
print()
print("====================================")
print("기준값을 계산합니다.")
print("20번 측정하여 평균을 계산합니다.")
print("====================================")

total = 0

for i in range(20):

    value = mq2.read_u16()

    total += value

    time.sleep_ms(50)


# 기준값
baseline = total // 20


print()
print("====================================")
print("기준값 설정 완료!")
print("기준값 :", baseline)
print("====================================")
print()


# ==========================================
# 8. 기준값 설정 이후 계속 측정
# ==========================================
while True:

    total = 0

    # --------------------------------------
    # 20번 측정
    # --------------------------------------
    for i in range(20):

        value = mq2.read_u16()

        total += value

        time.sleep_ms(50)


    # --------------------------------------
    # 20번 측정값의 평균
    # --------------------------------------
    average = total // 20


    # --------------------------------------
    # 기준값보다 얼마나 증가했는지 계산
    # --------------------------------------
    difference = average - baseline


    # --------------------------------------
    # 기준값 이하이면 LED 0칸
    # --------------------------------------
    if difference <= 0:

        led_count = 0

    else:

        # ----------------------------------
        # +10 증가할 때마다 LED 1칸 증가
        # ----------------------------------
        led_count = difference // 10


    # --------------------------------------
    # 최대 10칸까지만 사용
    # --------------------------------------
    if led_count > 10:
        led_count = 10


    # --------------------------------------
    # LED 표시
    # --------------------------------------
    show_led(led_count)


    # --------------------------------------
    # 상태 표시
    # --------------------------------------
    if led_count <= 5:
        status = "좋음"

    elif led_count <= 8:
        status = "보통"

    else:
        status = "나쁨"


    # --------------------------------------
    # 결과 출력
    # --------------------------------------
    print("------------------------------------")
    print("기준값      :", baseline)
    print("현재 평균값 :", average)
    print("증가량      :", difference)
    print("LED         :", led_count, "칸")
    print("상태        :", status)
    print("------------------------------------")

    time.sleep(0.5)
